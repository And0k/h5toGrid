def test_no_duplicate_device_ids_from_yaml(
    temp_device_dir,
    info_yaml_with_non_normalized_ids,
    new_content_with_normalized_ids
):
    """
    Test that update_devices_meta_file does not create duplicate device IDs
    when merging from info_devices.yaml with non-normalized IDs.

    Scenario:
    1. info_devices.yaml has: I03, incl04, W01 (non-normalized)
    2. New content has: i3, i4, w1 (normalized via normalize_device_id)
    3. Expected result: i3, i4, w1 (normalized, no duplicates)
    """
    # Call update_devices_meta_file to merge the content
    result = update_devices_meta_file(
        device_dir=temp_device_dir,
        content=new_content_with_normalized_ids
    )

    # Verify that the file was created/updated
    assert result is True, "update_devices_meta_file should return True"

    # Read the created file
    output_file = temp_device_dir / DEVICES_FILE_NAME_UPD
    assert output_file.exists(), "Output file should exist"

    output_content = read_metadata_file(output_file)

    # Verify that we have exactly 3 devices (not 6)
    assert len(output_content) == 3, (
        f"Expected 3 devices in output, got {len(output_content)}. "
        f"Devices: {list(output_content.keys())}"
    )

    # Verify that all device IDs are normalized (no leading zeros)
    expected_device_ids = {"i3", "i4", "w1"}
    actual_device_ids = set(output_content.keys())

    assert actual_device_ids == expected_device_ids, (
        f"Expected normalized device IDs {expected_device_ids}, "
        f"got {actual_device_ids}"
    )

    # Verify that non-normalized IDs are NOT present
    assert "I03" not in actual_device_ids, "Non-normalized 'I03' should not be present"
    assert "incl04" not in actual_device_ids, "Non-normalized 'incl04' should not be present"
    assert "W01" not in actual_device_ids, "Non-normalized 'W01' should not be present"


def test_merge_device_metadata_helper_function():
    """
    Test the _merge_device_metadata helper function directly to ensure
    it correctly handles normalization and prevents duplicates.
    """
    # Existing content with normalized IDs (same as in info_devices@meta_finder.yaml)
    existing_content = {
        "i03": ["?", "?", "?", "?", "?", "?", "?", "?", "?", "?", "?"],
        "i04": ["?", "?", "?", "?", "?", "?", "?", "?", "?", "?", "?"],
    }

    # New content with normalized IDs (same devices, updated values)
    new_content = {
        "i03": ["1", "10", "5", "", "55.5", "21.5", "2023-01-01 00:00:00",
                 "2023-01-02 00:00:00", "300", "10", "Test"],
        "i04": ["2", "15", "7", "", "55.6", "21.6", "2023-01-01 00:00:00",
                 "2023-01-02 00:00:00", "300", "10", "Test2"],
        "w01": ["3", "20", "10", "", "55.7", "21.7", "2023-01-01 00:00:00",
                 "2023-01-02 00:00:00", "600", "5", "Test3"],
    }

    # Merge with normalize_keys=False (as when merging from existing info_devices@meta_finder.yaml)
    merged = _merge_device_metadata(
        existing_content,
        new_content,
        normalize_keys=False
    )

    # Verify no duplicates
    assert len(merged) == 3, (
        f"Expected 3 devices after merge, got {len(merged)}. "
        f"Devices: {list(merged.keys())}"
    )

    # Verify all IDs are present
    expected_ids = {"i03", "i04", "w01"}
    actual_ids = set(merged.keys())
    assert actual_ids == expected_ids, (
        f"Expected IDs {expected_ids}, got {actual_ids}"
    )

    # Verify that merged content has the new values (not placeholders)
    # Merged devices get nested station dict structure: {"0": [values]}
    assert merged["i03"]["0"][0] == "1", "i03 should have new point value"
    assert merged["i04"]["0"][0] == "2", "i04 should have new point value"
    assert merged["w01"][0] == "3", "w01 should have new point value (new device, flat list)"


