def test_partial_update_preserves_non_placeholder_values(
    temp_device_dir,
    info_yaml_with_non_normalized_ids
):
    """
    Test that when merging, non-placeholder values from existing YAML
    are preserved even when new content has placeholders.
    """
    # Create new content with normalized IDs (i3, i4) matching normalize_device_id output.
    # i3 has placeholder time values so existing YAML non-placeholders should be preserved.
    new_content = {
        "i3": {
            "point": "1",
            "sea_depth": "10",
            "height_above_bottom": "5",
            "modification_symbol": "",
            "latitude": "55.5",
            "longitude": "21.5",
            "time_st": "?",  # Placeholder — existing YAML value should be kept
            "time_en": "?",  # Placeholder — existing YAML value should be kept
            "burst_dt": "?",
            "bursts_t": "?",
            "comment": "Test device",
        },
        "i4": {
            "point": "2",
            "sea_depth": "15",
            "height_above_bottom": "7",
            "modification_symbol": "",
            "latitude": "55.6",
            "longitude": "21.6",
            "time_st": "2023-01-01 00:00:00",
            "time_en": "2023-01-02 00:00:00",
            "burst_dt": "300",
            "bursts_t": "10",
            "comment": "Test device 2",
        },
    }

    # Update the YAML file to have non-placeholder time values for I03
    yaml_file = temp_device_dir / DEVICES_FILE_NAME_YAML
    from meta_finder.io_info_files import save_to_yaml_format
    yaml_content = {
        "I03": ["?", "?", "?", "?", "?", "?",
                  "2023-01-01 00:00:00",  # Non-placeholder
                  "2023-01-02 00:00:00",  # Non-placeholder
                  "?", "?", "?"],
        "incl04": ["?", "?", "?", "?", "?", "?", "?", "?", "?", "?", "?"],
    }
    save_to_yaml_format(yaml_content, yaml_file)

    # Call update_devices_meta_file
    result = update_devices_meta_file(
        device_dir=temp_device_dir,
        content=new_content
    )

    assert result is True, "update_devices_meta_file should return True"

    # Read the created file
    output_file = temp_device_dir / DEVICES_FILE_NAME_UPD
    output_content = read_metadata_file(output_file)

    # Verify exactly 2 devices (no duplicates from normalization mismatch)
    assert len(output_content) == 2, (
        f"Expected 2 devices, got {len(output_content)}: {list(output_content.keys())}"
    )

    # Verify that i3 has the non-placeholder time values from YAML preserved
    i3_data = output_content["i3"]
    assert i3_data["0"][6] == "2023-01-01 00:00:00", (
        "i3 should preserve non-placeholder time_st from YAML"
    )
    assert i3_data["0"][7] == "2023-01-02 00:00:00", (
        "i3 should preserve non-placeholder time_en from YAML"
    )

    # Verify that i4 has the new values from new_content
    i4_data = output_content["i4"]
    assert i4_data["0"][0] == "2", "i4 should have new point value"
    assert i4_data["0"][6] == "2023-01-01 00:00:00", "i4 should have new time_st value"


